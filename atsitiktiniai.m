
function masyvas = atsitiktiniai(n, N)
% ATSITIKTINIAI generuoja atsitiktiniu naturaliuju skaiciu masyva.
%   masyvas = atsitiktiniai(n, N)
%   n - generuojamu skaiciu kiekis.
%   N - didziausia galima skaiciaus reiksme.
%   masyvas - stulpelinis masyvas su reiksmemis nuo 1 iki N.

masyvas = randi(N, n, 1);

end


